import solc from "solc";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
const input = {
  language: "Solidity",
  sources: {
    "BeeHiveRegistry.sol": {
      content: readFileSync("contracts/BeeHiveRegistry.sol", "utf8"),
    },
  },
  settings: {
    optimizer: { enabled: true, runs: 200 },
    evmVersion: "paris",
    outputSelection: { "*": { "*": ["abi", "evm.bytecode"] } },
  },
};
const output = JSON.parse(solc.compile(JSON.stringify(input)));
for (const e of output.errors ?? []) {
  if (e.severity === "error") throw new Error(e.formattedMessage);
  console.warn(e.formattedMessage);
}
const contract = output.contracts["BeeHiveRegistry.sol"].BeeHiveRegistry;
mkdirSync("artifacts", { recursive: true });
writeFileSync(
  "artifacts/BeeHiveRegistry.json",
  JSON.stringify(
    { abi: contract.abi, bytecode: "0x" + contract.evm.bytecode.object },
    null,
    2,
  ),
);
writeFileSync(
  "packages/blockchain/src/abi.ts",
  "// Generated by npm run chain:compile from BeeHiveRegistry.sol\nexport const registryAbi = " +
    JSON.stringify(contract.abi, null, 2) +
    " as const;\n",
);
console.log("BeeHiveRegistry compiled; ABI exported.");
